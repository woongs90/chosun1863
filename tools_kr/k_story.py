def progress(label, pairs, done):
    from itertools import combinations
    flags = [f for f, _, _ in pairs]
    alts = []
    for k in range(len(pairs)):
        for got in combinations(range(len(pairs)), k):
            rest = [pairs[i] for i in range(len(pairs)) if i not in got]
            cond = {}
            if got: cond["flags"] = [pairs[i][0] for i in got]
            cond["noFlags"] = [f for f, _, _ in rest]
            alts.append({"if": cond, "then": [GOAL("%s (%s)" % (label, " · ".join(n for _, _, n in rest)), *[t for _, t, _ in rest])]})
    return {"if": {"flags": flags}, "then": done, "else": alts}

